# --- How to tell whether the parent unit really stored the firmware -----------
# The parent unit's drive is generated by its firmware. Data it keeps is written
# to flash at about 0.12 MB/s; data it discards is accepted at USB speed
# (>10 MB/s). The speed is checked over every rolling 1 MB window, so even a
# partly discarded copy is caught, and RESET must then not be pressed.
