"""Copy firmware.bin onto the parent unit the way Windows Explorer does.

The parent unit's drive is generated by its own firmware. It only keeps data that
is written into a file it already knows about, so the order matters and mirrors
Windows: create the directory entry, reserve the clusters, record the size, then
stream the data. Every write goes through WriteGuard, whose allowlist is fixed
from the plan before the first write.
"""

from __future__ import annotations

import math
import time
from collections import deque
from dataclasses import dataclass
from typing import Callable

from . import constants as C
from . import device, fat16

Say = Callable[[str], None]
DATA_CHUNK_SECTORS = 256  # 128 KiB per WRITE(10)
PROGRESS_STEP_BYTES = 2 * 1024 * 1024
DO_NOT_RESET = (
    "Do NOT press RESET. Turn the parent unit off and on again, then run the install again. "
    "This is the same advice Babysense gives for an interrupted update."
)


class InstallAborted(RuntimeError):
    """The install stopped before the firmware was fully handed over. RESET must not be pressed."""


class WriteGuard:
    """Passes writes to the device only inside sector ranges fixed when it is created."""

    def __init__(self, dev: device.BlockDevice, allowed: tuple[tuple[int, int], ...]) -> None:
        self._dev, self._allowed = dev, allowed
        self.attempted = False
        self.bytes_written = 0

    def write(self, lba: int, data: bytes) -> None:
        if not data or len(data) % C.BLOCK_SIZE:
            raise PermissionError(f"refused a write of {len(data)} bytes: not a whole number of sectors")
        count = len(data) // C.BLOCK_SIZE
        if not any(start <= lba and lba + count <= end for start, end in self._allowed):
            raise PermissionError(f"refused write to sectors {lba}..{lba + count - 1}: not in the plan")
        self.attempted = True
        self._dev.write10(lba, data)
        self.bytes_written += len(data)


def plan_ranges(plan: fat16.Plan) -> tuple[tuple[int, int], ...]:
    """Exactly the sectors the plan changes (contiguous runs merged), plus the file's data sectors."""
    metadata = tuple((start, start + count) for start, count in fat16.sector_runs(plan.changed_sectors))
    return metadata + ((plan.data_sector, plan.data_sector + plan.data_sectors),)


@dataclass(frozen=True)
class InstallResult:
    first_cluster: int
    clusters: int
    data_sector: int
    seconds: float
    megabytes_per_second: float
    flush: str
    warnings: tuple[str, ...]


def install(
    dev: device.BlockDevice,
    firmware: bytes,
    say: Say,
    allow_untested_device: bool = False,
    expect_capture: bool = True,
    clock: Callable[[], float] = time.monotonic,
    timestamp: float | None = None,
) -> InstallResult:
    """Hand `firmware` to the parent unit as firmware.bin. Raises InstallAborted on any problem."""
    info = device.identify(dev)
    warnings = tuple(device.check_supported(info, allow_untested_device))
    for warning in warnings:
        say(f"Warning: {warning}")
    geometry, metadata = device.read_metadata(dev)
    plan = fat16.make_plan(metadata, C.DEVICE_FIRMWARE_NAME, len(firmware), info.sectors, timestamp)
    say(
        f"Found the parent unit's update drive ({info.megabytes:.0f} MB). Plan: firmware.bin in "
        f"clusters {plan.first_cluster}-{plan.first_cluster + plan.cluster_count - 1}."
    )
    guard = WriteGuard(dev, plan_ranges(plan))
    try:
        _create_file(guard, metadata, geometry, plan, say)
        _confirm_registered(dev, plan, len(firmware))
        seconds, rate = _stream(guard, plan, firmware, say, clock, expect_capture)
        flush = _finish(dev, say)
    except InstallAborted:
        raise
    except BaseException as exc:  # noqa: BLE001 - after the first write, every failure must say "don't reset"
        if not guard.attempted:
            raise
        reason = str(exc) or type(exc).__name__
        raise InstallAborted(
            f"The transfer stopped after {guard.bytes_written / 1e6:.1f} MB ({reason}). {DO_NOT_RESET}"
        ) from exc
    return InstallResult(plan.first_cluster, plan.cluster_count, plan.data_sector, seconds, rate, flush, warnings)


def _write_sectors(guard: WriteGuard, image: bytes, sectors: list[int]) -> None:
    for start, count in fat16.sector_runs(sectors):
        guard.write(start, image[start * C.BLOCK_SIZE : (start + count) * C.BLOCK_SIZE])


def _create_file(guard: WriteGuard, metadata: bytes, g: fat16.Geometry, plan: fat16.Plan, say: Say) -> None:
    """Windows order: empty directory entry, then the cluster chain, then the final size."""
    entry_offset = g.first_root_sector * C.BLOCK_SIZE + plan.root_slot * fat16.DIR_ENTRY_SIZE
    planned_entry = plan.new_metadata[entry_offset : entry_offset + fat16.DIR_ENTRY_SIZE]
    empty_entry = planned_entry[:26] + b"\0" * 6  # same name/timestamps, no cluster, size 0
    say("Step 1 of 4: creating firmware.bin on the parent unit")
    _write_sectors(guard, fat16.with_root_entry(metadata, g, plan.root_slot, empty_entry), [plan.root_sector])
    say("Step 2 of 4: reserving space for it")
    _write_sectors(guard, plan.new_metadata, [s for s in plan.changed_sectors if s != plan.root_sector])
    say("Step 3 of 4: recording its size")
    _write_sectors(guard, plan.new_metadata, [plan.root_sector])


def _confirm_registered(dev: device.BlockDevice, plan: fat16.Plan, size: int) -> None:
    """The parent unit must now list firmware.bin with the right size, or no data is sent."""
    wanted = fat16.short_name(C.DEVICE_FIRMWARE_NAME)
    found = [e for e in fat16.parse_entries(dev.read10(plan.root_sector, 1)) if e.raw_name == wanted]
    if not any(e.size == size and e.first_cluster == plan.first_cluster for e in found):
        raise InstallAborted(
            f"The parent unit did not register firmware.bin, so no firmware data was sent. {DO_NOT_RESET}"
        )


def _too_fast(rate_bytes_per_s: float) -> InstallAborted:
    return InstallAborted(
        f"The parent unit accepted data at {rate_bytes_per_s / 1e6:.1f} MB/s, far faster than it can store it "
        f"(about 0.1 MB/s), so it most likely discarded some of it. {DO_NOT_RESET}"
    )


def _stream(
    guard: WriteGuard, plan: fat16.Plan, firmware: bytes, say: Say, clock: Callable[[], float], expect_capture: bool
) -> tuple[float, float]:
    """Write only the sectors that hold file data (like Windows), checking the speed of every 1 MB."""
    payload = firmware + b"\0" * (math.ceil(len(firmware) / C.BLOCK_SIZE) * C.BLOCK_SIZE - len(firmware))
    say("Step 4 of 4: sending the firmware (about 5 minutes; keep the cable connected)")
    chunk_bytes, start, next_report = DATA_CHUNK_SECTORS * C.BLOCK_SIZE, clock(), PROGRESS_STEP_BYTES
    window: deque[tuple[float, int]] = deque([(start, 0)])
    for offset in range(0, len(payload), chunk_bytes):
        guard.write(plan.data_sector + offset // C.BLOCK_SIZE, payload[offset : offset + chunk_bytes])
        sent, now = min(offset + chunk_bytes, len(payload)), clock()
        window.append((now, sent))
        while len(window) > 2 and sent - window[1][1] >= C.SPEED_WINDOW_BYTES:
            window.popleft()
        window_bytes, window_seconds = sent - window[0][1], max(now - window[0][0], 1e-9)
        if (
            expect_capture
            and window_bytes >= C.SPEED_WINDOW_BYTES
            and window_bytes / window_seconds > C.MAX_PLAUSIBLE_CAPTURE_MB_PER_S * 1e6
        ):
            raise _too_fast(window_bytes / window_seconds)
        if sent >= next_report or sent == len(payload):
            rate = sent / max(now - start, 1e-9)
            say(
                f"  {sent / 1e6:5.1f} of {len(payload) / 1e6:.1f} MB  ({rate / 1e6:.2f} MB/s, "
                f"about {(len(payload) - sent) / max(rate, 1.0):.0f}s left)"
            )
            next_report += PROGRESS_STEP_BYTES
    seconds = max(clock() - start, 1e-9)
    rate = len(payload) / seconds
    if expect_capture and rate > C.MAX_PLAUSIBLE_CAPTURE_MB_PER_S * 1e6:
        raise _too_fast(rate)
    return seconds, rate / 1e6


def _finish(dev: device.BlockDevice, say: Say) -> str:
    """Ask the unit to commit everything. A disconnect here still counts as an interrupted update."""
    say("Finishing: asking the parent unit to confirm everything is written (can take a few minutes)...")
    return dev.synchronize_cache()
